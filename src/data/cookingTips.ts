export function setTipReview(id:string,value:'keep'|'hide'|'pending'){const reviews=getTipReviews();if(value==='pending')delete reviews[id];else reviews[id]=value;localStorage.setItem('chef:tip-reviews:v1',JSON.stringify(reviews));return reviews;}
